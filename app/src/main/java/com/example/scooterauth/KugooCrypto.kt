    private val KEY_STRS = mapOf(
        1 to "09D01E69C13B8AF5B16501314ED8CE9B",
        2 to "3937EAD225021B8A52D8786B736D8B6D",
        3 to "AB31207F8DC7137434EDD37A888FA35D"
    )

    private fun string2char(s: String): IntArray {
        val n = s.length / 2
        return IntArray(n) { i -> s.substring(i * 2, i * 2 + 2).toInt(16) }
    }

    private fun bondingKeyGenerate(mode: Int): IntArray {
        val keyTmp = string2char(KEY_STRS.getValue(mode)).copyOf()
        for (i in 0 until 16) {
            keyTmp[i] = S_BOX[keyTmp[i] and 255]
        }
        // циклический сдвиг влево на 4 байта: keyTmp[4:] + keyTmp[:4]
        return IntArray(16) { i -> keyTmp[(i + 4) % 16] }
    }

    /**
     * nonceHex: 12 hex-символов (6 байт), присланные самокатом после "+PM>"
     * mode: 1, 2 или 3 — если один не подошёл, пробуй следующий
     * Возвращает 8-символьный HEX, который нужно отправить как "+PM<<hash>"
     */
    fun encryptToken(nonceHex: String, mode: Int): String {
        val nonce = string2char(nonceHex)
        val cArr = IntArray(32)

        for (i in 0 until 6) cArr[i] = nonce[i]
        for (i in 0 until 6) cArr[6 + i] = nonce[i]
        for (i in 0 until 4) cArr[12 + i] = nonce[i]
        for (i in 1 until 16) cArr[15 + i] = cArr[i] // cArr[16:31] = cArr[1:16]
        cArr[31] = cArr[0]

        val keyTmp = bondingKeyGenerate(mode)
        val invStr = string2char(INV_STRS.getValue(mode))

        for (c in 0 until 16) {
            cArr[c] = (cArr[c] xor keyTmp[c]) xor invStr[c]
            cArr[c + 16] = (cArr[c + 16] xor keyTmp[c]) xor invStr[c]
        }

        for (c2 in 1 until 16) {
            cArr[c2] = cArr[c2] xor cArr[c2 - 1]
            cArr[c2 + 16] = cArr[c2 + 16] xor cArr[c2 + 16 - 1]
        }

        val bondingHash = IntArray(4)
        for (c3 in 0 until 4) {
            val v = (cArr[c3] xor cArr[c3 + 4] xor cArr[c3 + 8] xor
                    (cArr[c3 + 12] + cArr[c3 + 16]) xor cArr[c3 + 20] xor cArr[c3 + 24] xor cArr[c3 + 28])
            bondingHash[c3] = v and 255
        }

        return bondingHash.joinToString("") { String.format("%02X", it) }
    }
